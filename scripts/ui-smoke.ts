import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { createApp } from '../server/index';

const temporary = await mkdtemp(path.join(os.tmpdir(), 'crawlspace-ui-'));
const {app,engine,store} = await createApp({statePath:path.join(temporary,'state.json'),demoStepMs:80});
const apiServer = app.listen(0,'127.0.0.1');
await new Promise<void>(resolve=>apiServer.once('listening',resolve));
const address = apiServer.address();
assert(address&&typeof address!=='string');
const target=`http://127.0.0.1:${address.port}`;
const vite=await createServer({server:{host:'127.0.0.1',port:5188,strictPort:true,proxy:{'/api':target}}});
await vite.listen();
let browser;
try {
 try {browser=await chromium.launch({channel:'msedge',headless:true});}
 catch {browser=await chromium.launch({headless:true});}
 const page=await browser.newPage({viewport:{width:1512,height:1000}});
 const errors:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5188',{waitUntil:'domcontentloaded',timeout:60_000});
 await page.getByText('Local runner ready',{exact:true}).waitFor();
 await page.locator('.react-flow__node').first().waitFor();
 assert.equal(await page.locator('.react-flow__node').count(),5);
 await mkdir('.crawlspace/previews',{recursive:true});
 await page.screenshot({path:'.crawlspace/previews/builder.png',fullPage:true});
 await page.getByRole('button',{name:'Instructions',exact:true}).click();
 const persona=page.getByRole('textbox',{name:'Who is this agent?'});
 await persona.fill('You are a precise code reviewer. Verify every observation.');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await page.getByText('Workflow saved',{exact:true}).waitFor();
 assert.equal(store.get().workflow.nodes[0].data.persona,'You are a precise code reviewer. Verify every observation.');
 await page.getByRole('button',{name:'Add agent',exact:true}).click();
 await page.getByRole('button',{name:/Custom agent Your role/}).click();
 assert.equal(await page.locator('.react-flow__node').count(),6);
 await page.getByRole('button',{name:'Remove',exact:true}).click();
 assert.equal(await page.locator('.react-flow__node').count(),5);
 await page.getByRole('button',{name:'Workflow settings',exact:true}).click();
 await page.getByLabel('Run mode',{exact:true}).selectOption('once');
 await page.getByRole('button',{name:'Save settings',exact:true}).click();
 await page.getByRole('button',{name:'Run demo',exact:true}).click();
 await page.waitForFunction(async()=>{const s=await (await fetch('/api/state')).json();return s.runs[0]?.status==='completed';});
 assert.equal(store.get().runs[0].steps,5);
 assert.equal(store.get().findings.length,3);
 await page.getByRole('button',{name:/^Findings/}).click();
 await page.getByRole('heading',{name:'Demo: low-contrast secondary text',exact:true}).waitFor();
 await page.getByRole('combobox',{name:'Status of Demo: low-contrast secondary text',exact:true}).selectOption('resolved');
 await page.waitForFunction(async()=>{const s=await (await fetch('/api/state')).json();return s.findings.some((f:{status:string})=>f.status==='resolved');});
 await page.screenshot({path:'.crawlspace/previews/findings.png',fullPage:true});
 await page.getByRole('button',{name:'Team messages',exact:true}).click();
 await page.getByRole('textbox',{name:'Your message',exact:true}).fill('Please verify the empty-state behavior and report file evidence.');
 await page.getByRole('button',{name:'Send message',exact:true}).click();
 await page.getByText('Please verify the empty-state behavior and report file evidence.',{exact:true}).waitFor();
 assert.equal(store.get().messages.at(-1)?.from,'you');
 await page.getByRole('button',{name:'Your team',exact:true}).click();
 assert.equal(await page.locator('.staff-card').count(),5);
 await page.getByRole('button',{name:'Models',exact:true}).click();
 await page.getByRole('button',{name:'Add model',exact:true}).click();
 await page.getByLabel('Display name',{exact:true}).fill('Smoke test model');
 await page.getByLabel('Model ID',{exact:true}).fill('qwen3:4b');
 await page.getByRole('button',{name:'Save model',exact:true}).click();
 await page.getByRole('heading',{name:'Smoke test model',exact:true}).waitFor();
 assert.equal(store.get().models.length,3);
 await page.getByRole('button',{name:'Remove Smoke test model',exact:true}).click();
 await page.getByRole('button',{name:'Remove model',exact:true}).click();
 await page.waitForFunction(async()=>{const s=await (await fetch('/api/state')).json();return s.models.length===2;});
 await page.screenshot({path:'.crawlspace/previews/models.png',fullPage:true});
 await page.getByRole('button',{name:'Workflow builder',exact:true}).click();
 await page.getByRole('button',{name:'Run demo',exact:true}).click();
 await page.getByRole('button',{name:'Stop run',exact:true}).click();
 await page.waitForFunction(async()=>{const s=await (await fetch('/api/state')).json();return s.runs[0]?.status==='stopped';});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'.crawlspace/previews/mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 assert.equal(overflow,false,'Mobile layout must not overflow horizontally');
 assert.deepEqual(errors,[],'No browser runtime errors');
 console.log('UI smoke passed: graph editing, saved persona, settings, demo traversal, finding status, messaging, model CRUD, stop, responsive layout.');
} finally {
 await browser?.close();await vite.close();await engine.stop();await engine.waitForIdle();await store.flush();
 await new Promise<void>(resolve=>apiServer.close(()=>resolve()));
 assert.equal(path.dirname(path.resolve(temporary)),path.resolve(os.tmpdir()));
 assert(path.basename(temporary).startsWith('crawlspace-ui-'));
 await rm(temporary,{recursive:true,force:true});
}
